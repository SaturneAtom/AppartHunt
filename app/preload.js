// Pont sécurisé entre la fenêtre et le processus principal.
const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("apparthunt", {
  snapshot: () => ipcRenderer.invoke("snapshot"),
  profil: () => ipcRenderer.invoke("profil"),
  ask: (prompt, screen, chat, opts) => ipcRenderer.invoke("ask", prompt, screen, chat, opts),
  agentEtat: () => ipcRenderer.invoke("agent-etat"),
  chats: () => ipcRenderer.invoke("chats"),
  newChat: titre => ipcRenderer.invoke("chat-new", titre),
  openChat: id => ipcRenderer.invoke("chat-open", id),
  renameChat: (id, titre) => ipcRenderer.invoke("chat-rename", id, titre),
  deleteChat: id => ipcRenderer.invoke("chat-delete", id),
  chatLog: id => ipcRenderer.invoke("chat-log", id),
  saveChat: (id, html) => ipcRenderer.send("chat-save", id, html),
  stop: () => ipcRenderer.invoke("stop"),
  placeBrowser: rect => ipcRenderer.send("browser-place", rect),
  openInBrowser: url => ipcRenderer.send("browser-open", url),
  browserBack: () => ipcRenderer.send("browser-back"),
  onBrowserShow: cb => ipcRenderer.on("browser-show", () => cb()),
  onBrowserUrl: cb => ipcRenderer.on("browser-url", (_e, info) => cb(info)),
  onBrowserAds: cb => ipcRenderer.on("browser-ads", (_e, ads) => cb(ads)),
  setBadges: map => ipcRenderer.send("browser-badges", map),
  choose: (url, val) => ipcRenderer.invoke("choose", url, val),
  candidature: (url, etat) => ipcRenderer.invoke("candidature", url, etat),
  onAgent: fn => ipcRenderer.on("agent-event", (_e, ev, chat) => fn(ev, chat)),
  onQuestion: fn => ipcRenderer.on("question", (_e, q) => fn(q)),
  answer: (id, text) => ipcRenderer.send("answer", id, text),
  onPlan: fn => ipcRenderer.on("plan", (_e, chat, etapes) => fn(chat, etapes)),
  onProposition: fn => ipcRenderer.on("proposition", (_e, chat, p) => fn(chat, p)),
  veille: cmd => ipcRenderer.invoke("veille", cmd),
  activite: () => ipcRenderer.invoke("activite"),
  activiteDetail: id => ipcRenderer.invoke("activite-detail", id),
  sessions: () => ipcRenderer.invoke("sessions"),
  session: id => ipcRenderer.invoke("session", id),
  sessionsCherche: q => ipcRenderer.invoke("sessions-cherche", q),
  sessionFichier: id => ipcRenderer.invoke("session-fichier", id),
  onActivite: fn => ipcRenderer.on("activite-maj", () => fn()),
  onVeille: fn => ipcRenderer.on("veille-etat", (_e, etat) => fn(etat)),
  onVeilleDemande: fn => ipcRenderer.on("veille-demande", (_e, texte) => fn(texte)),
  onData: fn => ipcRenderer.on("data-changed", (_e, s) => fn(s)),
  onReloading: cb => ipcRenderer.on("reloading", (_e, what) => cb(what)),
  onNotice: cb => ipcRenderer.on("app-notice", (_e, text) => cb(text)),
  onEcran: fn => ipcRenderer.on("ecran", (_e, ecran, s) => fn(ecran, s)),
});
